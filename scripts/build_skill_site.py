#!/usr/bin/env python3
"""Generate the local MkDocs source tree from the repository's canonical files."""
from __future__ import annotations

import html
import json
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path
from urllib.parse import quote

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "skills"
WEBSITE_DIR = REPO_ROOT / "website"
CONTENT_DIR = WEBSITE_DIR / "content"
GENERATED_DIR = WEBSITE_DIR / ".generated"
MARKER = ".generated-by-build_skill_site"
_REPOSITORY_URL: str | None = None

sys.path.insert(0, str(REPO_ROOT / "scripts"))
from scan_skill_issues import parse_frontmatter  # noqa: E402


def markdown_cell(value: object) -> str:
    return re.sub(r"\s+", " ", str(value)).strip().replace("|", r"\|")


def read_skill_metadata(skill_dir: Path) -> tuple[dict[str, str], str]:
    path = skill_dir / "SKILL.md"
    text = path.read_text(encoding="utf-8")
    metadata = parse_frontmatter(text)
    return metadata, text


def read_categories(skill_dirs: list[Path]) -> dict[str, list[str]]:
    readme = (REPO_ROOT / "README.md").read_text(encoding="utf-8")
    categories: dict[str, list[str]] = {}
    category: str | None = None
    in_skills_section = False

    for line in readme.splitlines():
        if line == "## Skills":
            in_skills_section = True
            continue
        if in_skills_section and line.startswith("## "):
            break
        if not in_skills_section:
            continue
        if line.startswith("### "):
            category = line[4:].strip()
            categories.setdefault(category, [])
            continue
        if category:
            for skill_name in re.findall(r"skills/(kmp-[a-z0-9-]+)/", line):
                if skill_name not in categories[category]:
                    categories[category].append(skill_name)

    known = {directory.name for directory in skill_dirs}
    categorized = {name for names in categories.values() for name in names}
    missing = sorted(known - categorized)
    unknown = sorted(categorized - known)
    if missing or unknown:
        raise RuntimeError(
            "README skill categories and skill folders disagree; "
            f"unlisted={missing}, unknown={unknown}"
        )
    return categories


def repository_url() -> str:
    global _REPOSITORY_URL
    if _REPOSITORY_URL is not None:
        return _REPOSITORY_URL

    try:
        result = subprocess.run(
            ["git", "remote", "get-url", "origin"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        _REPOSITORY_URL = "https://github.com/ronjunevaldoz/kmp-agent-skills"
        return _REPOSITORY_URL

    remote = result.stdout.strip()
    if remote.startswith("git@github.com:"):
        remote = "https://github.com/" + remote.removeprefix("git@github.com:")
    elif remote.startswith("ssh://git@github.com/"):
        remote = "https://github.com/" + remote.removeprefix("ssh://git@github.com/")
    _REPOSITORY_URL = remote.removesuffix(".git").rstrip("/")
    return _REPOSITORY_URL


def source_url(path: str) -> str:
    return f"{repository_url()}/blob/main/{quote(path, safe='/-._')}"


def reset_generated_tree() -> None:
    if GENERATED_DIR.exists():
        if GENERATED_DIR.resolve().parent != WEBSITE_DIR.resolve():
            raise RuntimeError(f"Refusing to clear unexpected path: {GENERATED_DIR}")
        if not (GENERATED_DIR / MARKER).is_file():
            raise RuntimeError(
                f"Refusing to overwrite {GENERATED_DIR}; remove it only if it is generated site output"
            )
        shutil.rmtree(GENERATED_DIR)

    GENERATED_DIR.mkdir(parents=True)
    (GENERATED_DIR / MARKER).write_text("Generated by scripts/build_skill_site.py\n", encoding="utf-8")
    shutil.copytree(CONTENT_DIR, GENERATED_DIR, dirs_exist_ok=True)


def skill_page_text(text: str, skill_name: str) -> str:
    lines = text.splitlines()
    body_start = 0
    if lines and lines[0].strip() == "---":
        for index in range(1, len(lines)):
            if lines[index].strip() == "---":
                body_start = index + 1
                break

    frontmatter = lines[:body_start]
    body = "\n".join(lines[body_start:]).lstrip("\n")
    body = body.replace("](../../README.md)", "](../../index.md)")
    source = source_url(f"skills/{skill_name}/SKILL.md")
    source_note = f"[View source `SKILL.md`]({source})"

    if frontmatter:
        return "\n".join(frontmatter) + "\n\n" + source_note + "\n\n" + body + "\n"
    return source_note + "\n\n" + body + "\n"


def render_catalog(skill_dirs: list[Path], categories: dict[str, list[str]]) -> str:
    skills = {directory.name: read_skill_metadata(directory)[0] for directory in skill_dirs}
    lines = [
        "# Skill catalog",
        "",
        f"**{len(skills)} skills** grouped using the repository's README categories.",
        "Search this page or any skill page for a skill name, trigger, API, or topic.",
        "",
    ]

    for category, names in categories.items():
        lines.extend([f"## {category} ({len(names)})", "", "| Skill | Purpose |", "|---|---|"])
        for name in names:
            metadata = skills[name]
            display_name = metadata.get("name", name)
            description = re.sub(r"`([^`]*)`", r"\1", metadata.get("description", ""))
            description = markdown_cell(textwrap.shorten(description, width=200, placeholder="…"))
            lines.append(f"| [`{display_name}`]({name}/index.md) | {description} |")
        lines.append("")
    return "\n".join(lines)


def render_routing_page() -> str:
    routing = json.loads((REPO_ROOT / "routing_rules.json").read_text(encoding="utf-8"))
    lines = [
        "# How skills are selected",
        "",
        "This page is generated from `routing_rules.json`. It describes the fast-path index;",
        "each skill's `SKILL.md` remains authoritative for its trigger keywords and details.",
        "",
        "## Priority order",
        "",
    ]
    lines.extend(["| Order | Routing stage |", "|---:|---|"])
    for item in routing.get("precedence", []):
        match = re.match(r"(\d+)\.\s*(.*)", item)
        if match:
            lines.append(f"| {match.group(1)} | {markdown_cell(match.group(2))} |")
        else:
            lines.append(f"| — | {markdown_cell(item)} |")

    scope = routing.get("project_skill_scope", {})
    lines.extend(["", "## Project and technology scope", ""])
    lines.extend(f"- {item}" for item in scope.get("precedence", []))
    if scope.get("negative_scope"):
        lines.extend(["", f"**Boundary:** {scope['negative_scope']}"])

    file_routes = routing.get("file_extension_routes", [])
    lines.extend(["", "## File extension routes", "", "| Files | Condition | Skill |", "|---|---|---|"])
    for route in file_routes:
        extensions = ", ".join(route.get("ext", []))
        lines.append(
            f"| {markdown_cell(extensions)} | {markdown_cell(route.get('condition', ''))} "
            f"| `{markdown_cell(route.get('skill', ''))}` |"
        )

    path_routes = routing.get("path_heuristics", [])
    lines.extend(["", "## Path-based routes", "", "| Path | Skill | Why |", "|---|---|---|"])
    for route in path_routes:
        lines.append(
            f"| `{markdown_cell(route.get('path_glob', ''))}` "
            f"| `{markdown_cell(route.get('skill', ''))}` "
            f"| {markdown_cell(route.get('note', ''))} |"
        )

    intent_routes = routing.get("intent_routes", {})
    lines.extend(["", "## Intent routes", "", "| Skill | Example triggers |", "|---|---|"])
    for skill, phrases in intent_routes.items():
        if skill.startswith("$"):
            continue
        lines.append(f"| `{markdown_cell(skill)}` | {markdown_cell(', '.join(phrases))} |")

    boundaries = routing.get("hard_boundaries", [])
    lines.extend(["", "## Hard boundaries", ""])
    lines.extend(f"- {item}" for item in boundaries)
    lines.extend(
        [
            "",
            "For the full skill workflow, open that skill's page in the [catalog](skills/index.md).",
            "",
        ]
    )
    return "\n".join(lines)


def render_quality_page() -> tuple[str, dict]:
    scan_path = REPO_ROOT / "scripts" / "scan_skill_issues.py"
    result = subprocess.run(
        [sys.executable, str(scan_path)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode not in (0, 1):
        raise RuntimeError(f"Skill issue scan failed:\n{result.stderr or result.stdout}")
    try:
        report = json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise RuntimeError(f"Could not parse skill issue scan output: {error}") from error

    total = int(report.get("total_issues", 0))
    blocking = int(report.get("blocking_issues", total))
    known_debt = total - blocking
    counts = report.get("by_severity", {})
    validators = [
        (
            "Repository structural audit",
            [sys.executable, str(REPO_ROOT / "skills/kmp-audit/scripts/audit_skills_repo.py"), str(REPO_ROOT)],
        ),
        (
            "Skill map coverage",
            [
                sys.executable,
                str(REPO_ROOT / "skills/kmp-expert/scripts/validate_skill_map.py"),
                "--repo-root",
                str(REPO_ROOT),
            ],
        ),
        (
            "Keyword routing coverage",
            [
                sys.executable,
                str(REPO_ROOT / "skills/kmp-expert/scripts/validate_keyword_routing.py"),
                "--repo-root",
                str(REPO_ROOT),
            ],
        ),
    ]
    validator_results = []
    for label, command in validators:
        check = subprocess.run(
            command,
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
        )
        output = (check.stdout or check.stderr).strip()
        validator_results.append((label, check.returncode == 0, output))

    lines = [
        "# Quality snapshot",
        "",
        f"Generated **{report.get('generated', 'unknown date')}** from `scripts/scan_skill_issues.py`.",
        "",
        "| Measure | Count |",
        "|---|---:|",
        f"| Findings | {total} |",
        f"| Blocking findings | {blocking} |",
        f"| Tracked known debt | {known_debt} |",
        f"| High severity | {counts.get('HIGH', 0)} |",
        f"| Medium severity | {counts.get('MEDIUM', 0)} |",
        f"| Low severity | {counts.get('LOW', 0)} |",
        "",
        "## Validation status",
        "",
        "| Check | Status | Details |",
        "|---|---|---|",
        f"| Skill issue scan | {'Pass' if blocking == 0 else 'Needs attention'} "
        f"| {blocking} blocking, {known_debt} tracked-debt findings |",
    ]
    for label, passed, output in validator_results:
        lines.append(
            f"| {markdown_cell(label)} | {'Pass' if passed else 'Needs attention'} "
            f"| {markdown_cell(output) if output else '—'} |"
        )
    lines.extend(
        [
            "",
            "The scanner covers documented structural and maintenance signals. It does not prove",
            "that every technical recommendation is correct. The repository validation workflow",
            "runs these same checks and the test suite on pushes and pull requests.",
            "",
        ]
    )

    known_issues = report.get("open_known_issues", [])
    if known_issues:
        lines.extend(["## Open known issues", ""])
        known_url = source_url("KNOWN_ISSUES.md")
        lines.extend(f"- [{markdown_cell(item)}]({known_url})" for item in known_issues)
        lines.append("")

    issues = report.get("issues", [])
    if not issues:
        lines.extend(["## Findings", "", "No findings in this scan.", ""])
    else:
        priority = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
        issues = sorted(
            issues,
            key=lambda issue: (
                priority.get(issue.get("severity", "LOW"), 3),
                issue.get("skill", "").casefold(),
                issue.get("check", ""),
            ),
        )
        lines.extend(["## Findings", ""])
        for issue in issues:
            skill_dir = issue.get("skill_dir", "")
            skill_name = issue.get("skill", skill_dir)
            if skill_dir.startswith("kmp-"):
                source_path = f"skills/{skill_dir}/SKILL.md"
                source_label = f"[`{skill_name}`](skills/{skill_dir}/index.md)"
            elif str(skill_name).startswith("/"):
                command = str(skill_name).lstrip("/")
                source_path = f"commands/{command}.md"
                source_label = f"[`{skill_name}`]({source_url(source_path)})"
            else:
                source_path = f"skills/{skill_dir}/SKILL.md"
                source_label = f"`{skill_name}`"

            summary = markdown_cell(
                f"{issue.get('severity', 'LOW')} · {skill_name} · "
                f"{issue.get('check', 'finding')} — {issue.get('detail', '')}"
            )
            prompt = html.escape(str(issue.get("prompt_hint", "")))
            lines.extend(
                [
                    "<details>",
                    f"<summary>{summary}</summary>",
                    "",
                    f"**Source:** {source_label} · [view file]({source_url(source_path)})",
                    "",
                    "<pre><code>" + prompt + "</code></pre>",
                    "",
                    "</details>",
                    "",
                ]
            )

    lines.extend(
        [
            "## Run the checks locally",
            "",
            "```powershell",
            "python scripts/scan_skill_issues.py",
            "python skills/kmp-audit/scripts/audit_skills_repo.py .",
            "python skills/kmp-expert/scripts/validate_skill_map.py --repo-root .",
            "python skills/kmp-expert/scripts/validate_keyword_routing.py --repo-root .",
            "```",
            "",
        ]
    )
    return "\n".join(lines), report


def build() -> tuple[int, int]:
    skill_dirs = sorted(
        path for path in SKILLS_DIR.iterdir() if path.is_dir() and (path / "SKILL.md").is_file()
    )
    categories = read_categories(skill_dirs)
    reset_generated_tree()

    generated_skills = GENERATED_DIR / "skills"
    generated_skills.mkdir(parents=True, exist_ok=True)
    for skill_dir in skill_dirs:
        destination = generated_skills / skill_dir.name
        shutil.copytree(
            skill_dir,
            destination,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"),
        )
        metadata, text = read_skill_metadata(skill_dir)
        skill_file = destination / "SKILL.md"
        skill_file.unlink()
        (destination / "index.md").write_text(
            skill_page_text(text, skill_dir.name),
            encoding="utf-8",
        )

    (generated_skills / "index.md").write_text(
        render_catalog(skill_dirs, categories), encoding="utf-8"
    )
    (GENERATED_DIR / "routing.md").write_text(render_routing_page(), encoding="utf-8")
    quality_page, report = render_quality_page()
    (GENERATED_DIR / "quality.md").write_text(quality_page, encoding="utf-8")
    return len(skill_dirs), int(report.get("total_issues", 0))


def main() -> int:
    skill_count, issue_count = build()
    print(f"Generated docs for {skill_count} skills; quality snapshot has {issue_count} findings.")
    print(f"MkDocs source tree: {GENERATED_DIR.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
